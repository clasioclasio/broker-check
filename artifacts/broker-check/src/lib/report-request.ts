const NEUTRAL_REPORT_TEXTS = [
  'Для содержательного ответа необходимо сопоставить сведения о компании и уточнить детали вашего обращения. На этой странице нет заключения о её работе.',
  'Оценка ситуации требует отдельного рассмотрения документов и обстоятельств. По одному названию компании нельзя сделать вывод о её надёжности.',
  'Информация о компании может зависеть от её юридического названия, страны работы и условий договора. Подробный ответ требует индивидуального рассмотрения.',
  'Вопросы о работе компании следует рассматривать с учётом документов и конкретной ситуации. Этот экран не подтверждает ни наличие, ни отсутствие нарушений.',
  'Чтобы подготовить подробную информацию, необходимо уточнить сведения о компании и сопоставить доступные документы. Здесь не приводится оценка её деятельности.',
  'Название компании само по себе не позволяет оценить условия сотрудничества. Для подробного ответа требуется отдельное рассмотрение вашего запроса.',
] as const;

// A newly created report has a random UUID. Use it to choose wording once,
// without making an existing report change its message on reload.
export function getNeutralReportText(reportId: string): string {
  let hash = 0;
  for (const char of reportId) hash = (Math.imul(hash, 31) + char.charCodeAt(0)) >>> 0;
  return NEUTRAL_REPORT_TEXTS[hash % NEUTRAL_REPORT_TEXTS.length];
}

export function createReportRequest(company: string): string {
  return `Прошу подготовить подробную информацию о компании «${company.trim()}» и рассмотреть мой запрос. При необходимости прошу уточнить, какие сведения или документы нужны дополнительно. Готовый отчёт прошу направить мне в WhatsApp на указанный номер телефона.`;
}
